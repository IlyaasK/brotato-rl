/* Effective player weapon stats -- owner: WeaponStats.
 *
 * Implements the SOURCE effective-stat pipeline for a live player weapon slot:
 *   weapon_service.gd:35-63   init_melee_stats / init_ranged_stats (range)
 *   weapon_service.gd:88-132  _set_common_ranged_stats (spread/count/pierce/bounce/speed)
 *   weapon_service.gd:134-290 init_base_stats (the whole ordered modifier chain)
 *   weapon_service.gd:296-333 init_burning_data
 *   weapon_service.gd:489-495 apply_scaling_stats_to_damage / sum_scaling_stat_values
 *   weapon_service.gd:551-600 _apply_min_cooldown_effect / _apply_max_cooldown_effect
 *   weapon_service.gd:568-571 apply_attack_speed_mod_to_cooldown (MIN_COOLDOWN = 2)
 *   weapon_service.gd:608-625 _apply_weapon_scaling_stat_effects
 *   weapon.gd:345-347          update_current_spread (accuracy)
 *   weapons/weapon_stats/melee_weapon_stats.gd / ranged_weapon_stats.gd
 *   weapons/shooting_behaviors/{melee,ranged}_shooting_data.gd (cooldown frames)
 *   effects/items/{weapon_type_bonus_effect,class_bonus_effect,
 *                  weapon_cooldown_effect}.gd
 *   effects/weapons/{burning_effect,exploding_effect,weapon_stack_effect,
 *                    weapon_slow_on_hit_effect,
 *                    weapon_gain_stat_for_every_stat_effect}.gd
 *   dlc_1/dlc_1_data.gd:386-402 _boost_weapon_stats_damage / _boost_scaling_sats
 *
 * It reads the canonical weapon schema (brotato_weapons.h /
 * brotato_weapon_types.h, generated by WeaponData) and the canonical stat
 * layers (bt_core_stat_read / bt_core_stat_capped in brotato_core.h); it never
 * keeps a second copy of either.
 *
 * WHERE TO INCLUDE (parent): this header must be included by brotato_core.h
 * AFTER the stat/curse/scaling helpers (bt_core_stat_read at ~1658,
 * bt_curse_stat ~2521, bt_apply_atk_spd_mod_cd ~2529) and BEFORE bt_apply_item
 * (~2664), because bt_apply_item routes the weapon modifier keys through the
 * bt_wstats_*_add() helpers below. The Melee/Ranged/Inventory step modules then
 * include it (or rely on brotato_core.h) and call bt_weapon_stats().
 *
 * BtState FIELDS THIS MODULE READS (parent adds; no core/state edit here):
 *   Slot state (frozen by WeaponInventory):
 *     unsigned short wpn_id[BT_SLOTS];              canonical BT_WEAPONS row, BT_WEAPON_NONE = empty
 *     unsigned char  wpn_cursed[BT_SLOTS];
 *     float          wpn_wmod[BT_SLOTS];            per-copy weapon-STATS curse draw (dlc_1_data.gd:58-60)
 *     float          wpn_fxcurse[BT_SLOTS][BT_WEAPON_FX_CURSE_MAX];  per top-level effect curse draws (:62-67)
 *     float          wpn_cd[BT_SLOTS];              Weapon._current_cooldown, TICKS (owned by the step)
 *     unsigned char  wpn_count;                     dense live slots 0..wpn_count-1
 *   Read through WeaponInventory's accessors (bt_weapon_stats_curse_modifier /
 *   bt_weapon_fx_curse) -- never a fresh RNG draw here.
 *   Player-scoped modifier buckets (owned by THIS module; bt_apply_item fills
 *   them through the helpers at the bottom of this header):
 *     wtb_type/wtb_key/wtb_val + n_wtb              weapon_type_bonus  [type, prop, value]
 *     wcb_set/wcb_key/wcb_val  + n_wcb              weapon_class_bonus [set,  prop, value]
 *     soh_key/soh_val          + n_soh              slow_on_hit        [stat, value]
 *     wss_key/wss_pct          + n_wss              weapon_scaling_stats [stat, percent]
 *     min_wcd + n_min_wcd / max_wcd + n_max_wcd     minimum/maximum_weapon_cooldowns (ticks)
 *     mxp_x/mxp_nb + n_mxp                          item ModifyEveryXProjectile [x, sub-projectiles]
 *   Bucket overflow sets s->stat_reg_overflow (explicit, never a silent drop).
 *
 * Two optional WeaponData macros, used when present:
 *   BT_WEAPON_SOUND_COUNT(W)  the weapon's shooting_sounds.size() (bounds the
 *                             per-shot random sound RNG draw in the Ranged step).
 *   BT_ISTR_BOUNCE_DAMAGE / BT_ISTR_NEGATIVE_KNOCKBACK  interned effect keys.
 */
