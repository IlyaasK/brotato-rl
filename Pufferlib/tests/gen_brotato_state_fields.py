#!/usr/bin/env python3
"""Generate the BtState field table embedded in tests/test_brotato_cuda.cu.

The CUDA parity test diffs CPU and device state byte-for-byte over EVERY field
of BtState, and reports the first differing field by name. Keeping that list
hand-written would silently go stale whenever a field is added, so the table is
generated from the struct definition instead.

Usage (from the repository root):

    python3 tests/gen_brotato_state_fields.py \
        ocean/brotato/brotato_state.h > tests/brotato_state_fields.inc

tests/test_brotato_cuda.cu includes the result. The test asserts at runtime that the ranges are disjoint and that everything the
table does not cover is struct padding (266 bytes of 6,732,488 here), so a
stale or incomplete table is a hard failure rather than a silent gap.
"""

import re
import sys


def main() -> int:
    path = sys.argv[1]
    src = open(path).read()
    m = re.search(r"typedef struct BtState \{(.*?)\n\} BtState;", src, re.S)
    if not m:
        sys.stderr.write("BtState struct not found in %s\n" % path)
        return 1
    body = re.sub(r"/\*.*?\*/", " ", m.group(1), flags=re.S)
    body = re.sub(r"//[^\n]*", " ", body)

    fields, bad = [], []
    for decl in [d.strip() for d in body.split(";") if d.strip()]:
        decl = re.sub(r"([\[\]])", r" \1 ", decl)
        # A declarator list's commas may be glued to the preceding name
        # ("unsigned short a, b;"), which would hide every declarator but the
        # last from the start-of-list scan below; tokenize them explicitly.
        decl = re.sub(r",", " , ", decl)
        toks = " ".join(decl.split()).split()
        # The declarator list starts at the first identifier followed by ',',
        # '[' or nothing; everything before it is the (possibly multi-word) type.
        start = None
        for i, t in enumerate(toks):
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", t):
                continue
            nxt = toks[i + 1] if i + 1 < len(toks) else None
            if nxt is None or nxt == "," or nxt.startswith("["):
                start = i
                break
        if start is None or start == 0:
            bad.append(decl)
            continue
        for one in " ".join(toks[start:]).split(","):
            mm = re.fullmatch(r"([A-Za-z_][A-Za-z0-9_]*)\s*((?:\s*\[[^\]]*\])*)", one.strip())
            if not mm:
                bad.append(decl + "  ||  " + one)
                continue
            fields.append(mm.group(1))
    if bad:
        sys.stderr.write("unparsed declarations:\n  " + "\n  ".join(bad) + "\n")
        return 1
    if len(set(fields)) != len(fields):
        sys.stderr.write("duplicate field name\n")
        return 1
    # Self-contained: the test (and any other consumer) just includes this file
    # after declaring BtField.
    print("/* Generated by tests/gen_brotato_state_fields.py from")
    print(" * ocean/brotato/brotato_state.h -- do not edit by hand. %d fields. */" % len(fields))
    print("static const BtField BT_FIELDS[] = {")
    for name in fields:
        print('    { "%s", offsetof(BtState, %s), sizeof(((BtState *)0)->%s) },' % (name, name, name))
    print("};")
    print("#define BT_NFIELDS (sizeof(BT_FIELDS) / sizeof(BT_FIELDS[0]))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
