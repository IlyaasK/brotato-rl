static int g_step = 0;

static void fail(const std::string &what, int env = -1) {
    std::fprintf(stderr, "FAIL: %s (env %d, step %d)\n", what.c_str(), env, g_step);
    std::fflush(stderr);
    std::exit(1);
}
static void require(bool ok, const char *what, int env = -1) {
    if (!ok) fail(what, env);
}

static void ck(cudaError_t err, const char *what) {
    if (err != cudaSuccess) {
        std::fprintf(stderr, "CUDA error (%s): %s\n", what, cudaGetErrorString(err));
        std::exit(1);
    }
}

static bool feq(float a, float b) {
    unsigned int x, y;
    std::memcpy(&x, &a, 4);
    std::memcpy(&y, &b, 4);
    return x == y;                       // bit equality: NaN==NaN, -0 != +0
}
static unsigned int fbits(float f) {
    unsigned int b;
    std::memcpy(&b, &f, 4);
    return b;
}

// Deterministic, backend-independent action schedule: exercises every head
// value (hold, eight movement directions, shop and level-up indices, the six
// recycle and six combine weapon actions -> BT_ACTIONS total).
static int action_for(int step, int env) {
    unsigned int h = (unsigned int)step * 2654435761u ^ (unsigned int)(env + 1) * 40503u;
    h ^= h >> 13;
    h *= 2246822519u;
    h ^= h >> 16;
    return (int)(h % (unsigned int)BT_ACTIONS);
}

// The CPU environment's seed for env i on the GPU path (bt_gpu_init_kernel:
// rng = i; tag = 0; rng == 0 -> 1 + tag).
static unsigned long long seed_for(int i) {
    return (i == 0) ? 1ull : (unsigned long long)i;
}

// Deep locked-shop schedule (the regression DeepCudaFault found with
// compute-sanitizer): in the shop phase the LOCK actions are 21..24
// (brotato_progression.h:747 "21..24 toggle the lock of offer (action-21)") and 4
// is the REROLL that re-enters bt_progress_roll_shop's locked-offer snapshot.
// Even envs lock all four offers and then keep rerolling with the shop FULLY
// locked -- the state whose 4-entry snapshot store the device build mis-addressed
// (nl == 4 addresses the last element) and the state compute-sanitizer named.
// Odd envs lock offers 0 and 2 and reroll with them held, i.e. the same walk with
// nl == 2.  (The NON-CONTIGUOUS rank state that a ban leaves behind is not
// action-reachable here: banning an already locked offer is refused, observed as
// ban_tokens staying at 8, so that case stays with the directed-state test
// tests/test_brotato_shop_lock.cpp case [3].  A host-side build cannot see the
// fault at all: the CPU core is clean under ASan on both states.)
static const int BT_SHOP_LOCK_FULL[5] = {21, 22, 23, 24, 4};
static const int BT_SHOP_LOCK_SPARSE[5] = {21, 23, 4, 4, 4};

static Dict *make_kwargs(int zone, int shop_steps, const char *character, const char *weapon,
                         int endless, int audio_rng = 1, int start_wave = 0, int particles_rng = 1,
                         int warp_step = 0, int unlock_all = 1, int invulnerable = 0) {
    Dict *d = (Dict *)std::calloc(1, sizeof(Dict));
    d->name = dict_strdup("test_brotato_cuda");
    dict_set(d, "zone", (double)zone);
    dict_set(d, "shop_steps", (double)shop_steps);
    dict_set(d, "endless", (double)(endless ? 1 : 0));   // optional key; 0 == campaign
    // Optional key (brotato.h puf_init / brotato.cu puf_vec_create default it to
    // 1): 1 = the source's audio-RNG draws happen, 0 = the RL bridge's
    // audiovisual neutralization, where brotato_*_audio.h skips exactly those
    // draws.  Both backends must consume the identical Utils/main streams.
    dict_set(d, "audio_rng", (double)(audio_rng ? 1 : 0));
    // Optional key, honoured only when >= 1 by both backends (brotato.h puf_init
    // and brotato.cu puf_vec_create: dict_find + `value >= 1.0`), so a config
    // without it keeps bt_core_init's campaign default of wave 1.
    if (start_wave >= 1) dict_set(d, "start_wave", (double)start_wave);
    // Optional key, default 1 (brotato.h puf_init:484-487 / brotato.cu
    // puf_vec_create:327-330): 0 suppresses exactly the particles RNG draws.
    // No bt_core_init parameter; both wrappers write state.particles_rng after
    // init, so the host twin must do the same.
    dict_set(d, "particles_rng", (double)(particles_rng ? 1 : 0));
    // OPTIONAL experimental lane-scheduler selector (brotato.cu puf_vec_create:
    // `warp_step`, dict_find).  Only meaningful in a TU built with
    // -DBTFW_EXPERIMENTAL_LANE_SCHED; without it puf_vec_create forces the serial
    // path anyway (use_warp fallback), which is what the default 0 requests.
    if (warp_step) dict_set(d, "warp_step", 1.0);
    // Optional loot-pool profile (brotato.h puf_init:520-522 and
    // brotato.cu puf_vec_create / bt_gpu_init_kernel, both default 1): 1 = the
    // guide's fully unlocked pool, 0 = a fresh save's locked pool, which is a
    // different branch of the loot/shop roll.  Written unconditionally so the
    // key is part of every profile's contract; both wrappers accept >= 0.
    dict_set(d, "unlock_all", (double)(unlock_all ? 1 : 0));
    // DebugService.invulnerable (brotato.h puf_init:489-508 and brotato.cu
    // puf_vec_create:375-380 / bt_gpu_init_kernel:280, both default 0): 1
    // disables the player's Hurtbox, i.e. the demon cannot die.
    dict_set(d, "invulnerable", (double)(invulnerable ? 1 : 0));
    dict_set_str(d, "character", character);
    dict_set_str(d, "starting_weapon", weapon);
    return d;
}

// ---------------------------------------------------------------------------
// Complete BtState field table. Generated by
//   python3 tests/gen_brotato_state_fields.py ocean/brotato/brotato_state.h
// -- see that script. Byte-exact comparison of every field, so a new field
// cannot silently escape the parity check; the runtime check below proves the
// table is disjoint and that whatever it does not cover is struct padding.
// ---------------------------------------------------------------------------
typedef struct {
    const char *name;
    size_t off;
    size_t size;
} BtField;

// The field list is generated by tests/gen_brotato_state_fields.py from the
// struct text (regenerate with: python3 tests/gen_brotato_state_fields.py
// ocean/brotato/brotato_state.h > tests/brotato_state_fields.inc) and shared
// with the other brotato CUDA tools.
#include "brotato_state_fields.inc"

// Padding = the bytes of BtState no field covers. Those are never written by
// the core and their content in a cudaMalloc'ed device buffer is arbitrary, so
// they are reported separately instead of being compared. Everything else must
// match byte for byte.
static std::vector<unsigned char> g_covered;

static void init_coverage() {
    g_covered.assign(sizeof(BtState), 0);
    size_t overlap = 0, bytes = 0;
    for (size_t i = 0; i < BT_NFIELDS; i++) {
        const BtField &f = BT_FIELDS[i];
        require(f.off + f.size <= sizeof(BtState), "field range must lie inside BtState");
        for (size_t b = f.off; b < f.off + f.size; b++) {
            if (g_covered[b]) overlap++;
            g_covered[b] = 1;
        }
        bytes += f.size;
    }
    size_t covered = 0;
    for (size_t b = 0; b < g_covered.size(); b++) covered += g_covered[b];
    require(overlap == 0, "field table must be disjoint (union members would break byte comparison)");
    require(covered == bytes, "field table must not overlap");
    // A struct field the generator did not know about would show up as an
    // uncovered run far larger than the <=20-byte alignment holes seen here, so
    // a stale table fails loudly instead of silently skipping a new field.
    size_t run = 0, max_run = 0;
    for (size_t b = 0; b < g_covered.size(); b++) {
        if (g_covered[b]) { run = 0; continue; }
        run++;
        if (run > max_run) max_run = run;
    }
    // TIGHT: a parser hole looks exactly like padding (the pre-fix generator
    // tokenized on whitespace and hid every declarator but the last of a gloved
    // list like "unsigned short a, b, c;", so 213 real bytes were reported as
    // padding in runs up to 28 bytes). Real padding at this layout is 80 bytes
    // with the largest hole 4, so these bounds catch the observed hole class;
    // they are deliberately not a substitute for a correct parse - if this
    // fires, regenerate with the current tests/gen_brotato_state_fields.py
    // (its declarator split is the actual fix) and re-run.
    require(max_run <= 8 && sizeof(BtState) - covered <= 256,
            "field table looks stale or mis-parsed: an uncovered run is larger than struct padding "
            "(regenerate with the current tests/gen_brotato_state_fields.py)");
    std::printf("state table: %zu fields, %zu of %zu bytes covered, %zu bytes padding (largest hole %zu)\n",
                BT_NFIELDS, covered, sizeof(BtState), sizeof(BtState) - covered, max_run);
}

// Compare two BtState images. Returns "" if every field is byte-identical,
// otherwise a description of the first difference (field name, byte offset
// inside the field, hex of both sides). *pad_diff reports how many padding
// bytes differ (expected to be > 0 between a cudaMalloc'ed device copy and a
// zero-initialised host reference, and meaningless otherwise).
static std::string compare_state_bytes(const BtState &want, const BtState &got, size_t *pad_diff) {
    const unsigned char *w = (const unsigned char *)&want;
    const unsigned char *g = (const unsigned char *)&got;
    for (size_t i = 0; i < BT_NFIELDS; i++) {
        const BtField &f = BT_FIELDS[i];
        if (std::memcmp(w + f.off, g + f.off, f.size) == 0) continue;
        size_t off = 0;
        while (w[f.off + off] == g[f.off + off]) off++;
        char buf[256];
        // Report a scalar-sized window at the first differing byte so float and
        // integer fields both come out readable.
        unsigned long long wv = 0, gv = 0;
        size_t take = f.size - off < 8 ? f.size - off : 8;
        std::memcpy(&wv, w + f.off + off, take);
        std::memcpy(&gv, g + f.off + off, take);
        std::snprintf(buf, sizeof(buf), "field %s: first differing byte %zu (of %zu), host 0x%0*llx device 0x%0*llx",
                      f.name, off, f.size, (int)(take * 2), wv, (int)(take * 2), gv);
        return buf;
    }
    if (pad_diff) {
        size_t n = 0;
        for (size_t b = 0; b < sizeof(BtState); b++)
            if (!g_covered[b] && w[b] != g[b]) n++;
        *pad_diff = n;
    }
    return std::string();
}

// ---------------------------------------------------------------------------
// Batch: device buffers + the device Env array returned by puf_vec_create.
// ---------------------------------------------------------------------------
struct Batch {
    int n = 0;
    obs_t *obs_d = nullptr;
    float *act_d = nullptr, *rew_d = nullptr, *term_d = nullptr;
    unsigned char *mask_d = nullptr;
    Env *envs_d = nullptr;
    std::vector<float> obs_h, act_h, rew_h, term_h;
    std::vector<unsigned char> mask_h;   // n * BT_ACTIONS device mask rows
    std::vector<unsigned char> env_h;    // host mirrors of the device Env array
    Dict *kwargs = nullptr;
    const char *character = "";
    const char *weapon = "";

    Batch(int count, int zone, int shop_steps, const char *ch, const char *wp, int endless = 0,
          int audio_rng = 1, int start_wave = 0, int particles_rng = 1, int warp_step = 0,
          float wave_ovr = 0.0f, int unlock_all = 1, int invulnerable = 0)
        : n(count), character(ch), weapon(wp) {
        const size_t obytes = (size_t)n * BT_OBS_SIZE * sizeof(obs_t);
        const size_t sbytes = (size_t)n * sizeof(float);
        ck(cudaMalloc(&obs_d, obytes ? obytes : 4), "cudaMalloc(obs)");
        ck(cudaMalloc(&act_d, sbytes ? sbytes : 4), "cudaMalloc(actions)");
        ck(cudaMalloc(&rew_d, sbytes ? sbytes : 4), "cudaMalloc(rewards)");
        ck(cudaMalloc(&term_d, sbytes ? sbytes : 4), "cudaMalloc(terminals)");
        const size_t mbytes = (size_t)n * BT_ACTIONS;
        ck(cudaMalloc(&mask_d, mbytes ? mbytes : 4), "cudaMalloc(action mask)");
        ck(cudaMemset(mask_d, 1, mbytes ? mbytes : 1), "init action mask to 1");
        kwargs = make_kwargs(zone, shop_steps, ch, wp, endless, audio_rng, start_wave, particles_rng,
                             warp_step, unlock_all, invulnerable);
        envs_d = puf_vec_create(n, kwargs, obs_d, act_d, rew_d, term_d);
        require(envs_d != nullptr, "puf_vec_create must return the device Env base");
        puf_bind_action_mask(mask_d, BT_ACTIONS);
        obs_h.assign((size_t)n * BT_OBS_SIZE, 0.0f);
        mask_h.assign(mbytes, 1);
        act_h.assign((size_t)n, 0.0f);
        rew_h.assign((size_t)n, 0.0f);
        term_h.assign((size_t)n, 0.0f);
        env_h.assign((size_t)n * sizeof(Env), 0);
        // Replay-lane wave-duration override (`wave_ovr`, the instant_waves trace
        // hook): bt_core_init zeroes it, bt_core_reset preserves it, bt_enter_wave
        // reads it, and NEITHER wrapper has a kwargs path for it -- a replay boot
        // writes the state field after create, so the device twin of that write is
        // a direct patch of the device Env array.  puf_reset then re-enters the
        // wave on both sides, which is what rebuilds wave_duration/time_left from
        // the override (bt_gpu_reset_kernel -> bt_core_reset -> bt_enter_wave).
        if (wave_ovr > 0.0f) {
            pull_all_envs();
            for (int i = 0; i < n; i++)
                ((Env *)(env_h.data() + (size_t)i * sizeof(Env)))->state.wave_ovr = wave_ovr;
            ck(cudaMemcpy(envs_d, env_h.data(), (size_t)n * sizeof(Env), cudaMemcpyHostToDevice),
               "H2D envs (wave_ovr)");
            puf_reset(envs_d);
            ck(cudaDeviceSynchronize(), "wave_ovr reset sync");
        }
        pull_obs();
        pull_rewards();
    }
    ~Batch() {
        if (envs_d) puf_close(envs_d);
        cudaFree(obs_d);
        cudaFree(act_d);
        cudaFree(rew_d);
        cudaFree(term_d);
        cudaFree(mask_d);
    }

    void set_actions(const int *acts) {
        for (int i = 0; i < n; i++) act_h[i] = (float)acts[i];
        ck(cudaMemcpy(act_d, act_h.data(), (size_t)n * sizeof(float), cudaMemcpyHostToDevice), "H2D actions");
    }
    void step() {
        puf_step(envs_d);
        puf_bind_stream(0);
        ck(cudaDeviceSynchronize(), "step sync");
        // A step writes observations, rewards AND terminals, so refresh all
        // three here: forgetting one of them compares a stale host copy and
        // reports a difference that is not there.
        pull_obs();
        pull_rewards();
    }
    void reset() {
        puf_reset(envs_d);
        ck(cudaDeviceSynchronize(), "reset sync");
        // puf_reset rewrites observations, rewards and terminals for the fresh
        // episode exactly like puf_step rewrites them for a tick, so refresh the
        // host shadows here too (mirrors step()).  Leaving them stale made the
        // reset layer compare the POST-STEP obs buffer against the host's
        // post-reset observation and report a one-BT_DT difference in the
        // wave-time feature (obs[66]) that the device never produced: bt_core_reset
        // -> bt_enter_wave restores time_left = wave_duration and the wave clock
        // is history-independent (tests/test_brotato_core.cpp [63]).
        pull_obs();
        pull_rewards();
    }
    void pull_obs() {
        ck(cudaMemcpy(obs_h.data(), obs_d, (size_t)n * BT_OBS_SIZE * sizeof(obs_t), cudaMemcpyDeviceToHost), "D2H obs");
    }
    void pull_mask() {
        ck(cudaMemcpy(mask_h.data(), mask_d, mask_h.size(), cudaMemcpyDeviceToHost), "D2H mask");
    }
    void pull_rewards() {
        ck(cudaMemcpy(rew_h.data(), rew_d, (size_t)n * sizeof(float), cudaMemcpyDeviceToHost), "D2H rewards");
        ck(cudaMemcpy(term_h.data(), term_d, (size_t)n * sizeof(float), cudaMemcpyDeviceToHost), "D2H terminals");
    }
    void pull_env(int i) {
        bt_gpu_layout_pack(envs_d, i, 1);
        ck(cudaMemcpy(env_h.data() + (size_t)i * sizeof(Env), envs_d + i, sizeof(Env), cudaMemcpyDeviceToHost), "D2H env");
    }
    void pull_all_envs() {
        bt_gpu_layout_pack(envs_d, 0, n);
        ck(cudaMemcpy(env_h.data(), envs_d, (size_t)n * sizeof(Env), cudaMemcpyDeviceToHost), "D2H envs");
    }
    const Env *env(int i) const { return (const Env *)(env_h.data() + (size_t)i * sizeof(Env)); }
    const float *ob(int i) const { return obs_h.data() + (size_t)i * BT_OBS_SIZE; }
};

// Host reference batch: the same core, same seeds, same profile.
struct Ref {
    int n;
    std::vector<BtState> s;
    std::vector<float> obs, rew, term;
    Ref(int count, int zone, int shop_steps, unsigned short ch, unsigned short wp, int endless = 0,
        int audio_rng = 1, int start_wave = 0, int particles_rng = 1,
        const char *ch_name = "bull", const char *wp_name = "none", float wave_ovr = 0.0f,
        int unlock_all = 1, int invulnerable = 0)
        : n(count) {
        s.resize((size_t)n);
        obs.assign((size_t)n * BT_OBS_SIZE, 0.0f);
        rew.assign((size_t)n, 0.0f);
        term.assign((size_t)n, 0.0f);
        // brotato.h puf_init hands the *same* env kwargs to bt_reward_cfg_init
        // and the device path does the same once in puf_vec_create (posting the
        // resulting BtReward POD into the init kernel), so the host twin needs
        // its own kwargs -- and it must be the same dict: bt_reward_cfg_init's
        // defaults (gamma 0.99 among them) are what the device state carries,
        // and without this call every layer-A/C comparison fails on `rew`.
        Dict *rw_kwargs = make_kwargs(zone, shop_steps, ch_name, wp_name, endless, audio_rng, start_wave,
                                      particles_rng, 0, unlock_all, invulnerable);
        for (int i = 0; i < n; i++) {
            bt_core_init(&s[i], seed_for(i), zone, shop_steps, ch, wp, (unsigned char)audio_rng);
            // Mirrors brotato.h puf_init: the endless flag lives on the state and
            // persists across bt_core_reset (RunData.is_endless_run), so it is set
            // once here, after init, and never re-set by the reference's reset().
            if (endless) s[i].endless = 1;
            // Optional deep-start key, same rule as both host/device wrappers:
            // honoured only when >= 1, otherwise bt_core_init's wave-1 default.
            if (start_wave >= 1) s[i].start_wave = (unsigned short)start_wave;
            // Optional key, no bt_core_init parameter: brotato.h puf_init:496 and
            // brotato.cu bt_gpu_init_kernel:248 both write the state field after
            // init (default 1), so the twin does exactly that.
            s[i].particles_rng = (unsigned char)(particles_rng ? 1 : 0);
#if !defined(__CUDA_ARCH__)
            // CPU twin of the device's init-kernel reward cfg (brotato.h puf_init
            // calls bt_reward_cfg_init right after bt_core_init). Unconditional,
            // because the device applies rew_cfg to every env in
            // bt_gpu_init_kernel. Guarded because BT_HOST_ONLY erases
            // bt_reward_cfg_init in the device pass, which still parses this host
            // function (same guard as brotato.cu's puf_vec_create).
            bt_reward_cfg_init(&s[i], rw_kwargs);
#else
            (void)rw_kwargs;
#endif
            // Optional key, no bt_core_init parameter: both wrappers write the
            // state field after init, so the twin does the same.  unlock_all = 0
            // is the FRESH-SAVE loot pool (lock_default_items = 1), which the
            // device init kernel mirrors in bt_gpu_init_kernel.
            s[i].lock_default_items = (unsigned char)(unlock_all ? 0 : 1);
            // Same shape: both wrappers write state.invulnerable after init and
            // bt_core_reset does not clear it (brotato_core.h:2235 is init code).
            s[i].invulnerable = (unsigned char)(invulnerable ? 1 : 0);
            // Host twin of Batch's device patch: the replay lane writes wave_ovr
            // on the state after init, and the override only lands in bt_enter_wave,
            // so the twin re-enters the wave exactly like the device's post-patch
            // puf_reset (bt_core_reset preserves wave_ovr).  Both sides therefore
            // draw the same bt_enter_wave RNG and observe the same fresh wave.
            if (wave_ovr > 0.0f) {
                s[i].wave_ovr = wave_ovr;
                bt_core_reset(&s[i]);
            }
            bt_core_observe(&s[i], &obs[(size_t)i * BT_OBS_SIZE]);
        }
    }
    void reset(bool observe) {
        for (int i = 0; i < n; i++) {
            bt_core_reset(&s[i]);
            if (observe) bt_core_observe(&s[i], &obs[(size_t)i * BT_OBS_SIZE]);
            rew[i] = 0.0f;
            term[i] = 0.0f;
        }
    }
    void step(int i, int action) {
        bt_core_step(&s[i], action, &obs[(size_t)i * BT_OBS_SIZE], &rew[i], &term[i]);
    }
};

// Compare observations, rewards and terminals of a whole batch. Returns "" or a
// description of the first difference.
static std::string compare_batch(Batch &b, Ref &r) {
    // Refresh every device row compared below.  This function defines what
    // "device" means for the comparison, so it must not depend on the caller
    // having pulled the right buffer first: the reset layer used to compare a
    // stale post-step obs shadow against the host's post-reset observation.
    b.pull_obs();
    b.pull_rewards();
    // Action mask: the device rows must equal bt_action_mask of the same state
    // (the CPU env writes the identical bytes through brotato.h puf_step).
#if !BT_ENV_HAS_ACTION_MASK
    static bool told = false;
    if (!told) {
        told = true;
        std::printf("      [mask] the loaded ocean/brotato/brotato.cu does not implement "
                    "puf_bind_action_mask (PUF_HAS_ACTION_MASK_BIND): the device mask rows stay "
                    "all-ones and the mask comparison is skipped\n");
    }
#else
    b.pull_mask();
    for (int i = 0; i < b.n; i++) {
        // At create the device rows are UNWRITTEN: only puf_reset/puf_step call
        // bt_gpu_write_mask (bt_gpu_init_kernel does not), so a create-time
        // comparison only sees the harness' cudaMemset(1).  The CPU env has the
        // same property (brotato.h writes the mask from puf_reset/puf_step only),
        // so skip until the first tick has been taken.
        if (r.s[i].ticks == 0 && r.s[i].phase == 0) {
            static bool told = false;
            if (!told) {
                told = true;
                std::printf("      [mask] create-time rows are unwritten by both backends "
                            "(puf_reset/puf_step write them); comparing from the first tick\n");
            }
            continue;
        }
        unsigned char want[BT_ACTIONS];
        for (int a = 0; a < BT_ACTIONS; a++) want[a] = 0;
        bt_action_mask(const_cast<BtState *>(&r.s[i]), want);
        for (int a = 0; a < BT_ACTIONS; a++) {
            unsigned char got = b.mask_h[(size_t)i * BT_ACTIONS + a];
            if (got != want[a]) {
                char buf[160];
                std::snprintf(buf, sizeof(buf), "action mask[%d]: got %u want %u (phase %d)", a, got,
                              want[a], r.s[i].phase);
                return std::string(buf) + " (env " + std::to_string(i) + ")";
            }
        }
    }
#endif
    for (int i = 0; i < b.n; i++) {
        for (int j = 0; j < BT_OBS_SIZE; j++) {
            float got = b.ob(i)[j], want = r.obs[(size_t)i * BT_OBS_SIZE + j];
            if (!feq(got, want)) {
                char buf[200];
                std::snprintf(buf, sizeof(buf), "observation[%d]: got %.9g (0x%08x) want %.9g (0x%08x)", j,
                              got, fbits(got), want, fbits(want));
                return std::string(buf) + " (env " + std::to_string(i) + ")";
            }
        }
        if (!feq(b.rew_h[i], r.rew[i])) {
            char buf[160];
            std::snprintf(buf, sizeof(buf), "reward: got %.9g (0x%08x) want %.9g (0x%08x)", b.rew_h[i],
                          fbits(b.rew_h[i]), r.rew[i], fbits(r.rew[i]));
            return std::string(buf) + " (env " + std::to_string(i) + ")";
        }
        if (!feq(b.term_h[i], r.term[i])) {
            char buf[160];
            std::snprintf(buf, sizeof(buf), "terminal: got %.9g want %.9g", b.term_h[i], r.term[i]);
            return std::string(buf) + " (env " + std::to_string(i) + ")";
        }
    }
    return std::string();
}

static void require_state_equal(Batch &b, Ref &r, int env_index, size_t *pad_total, int step, const char *what) {
    g_step = step;
    char buf[256];
    std::snprintf(buf, sizeof(buf), "%s: CPU/CUDA state parity (env %d)", what, env_index);
    size_t pad = 0;
    std::string bad = compare_state_bytes(r.s[env_index], b.env(env_index)->state, &pad);
    if (pad_total) *pad_total += pad;
    if (!bad.empty()) fail(buf + std::string(": ") + bad, env_index);
}

// ---------------------------------------------------------------------------
// Cross-build trajectory digest. Replayed byte for byte by
// tests/brotato_traj_hash.cpp, which can be compiled with the flags build.sh
// uses for the CPU environment (clang -O2 -mavx2 -mfma, no -ffp-contract
// override). Comparing the three digests answers "does the CUDA backend agree
// with the CPU *build*, not just with this translation unit's host pass".
// ---------------------------------------------------------------------------
static unsigned long long g_traj = 1469598103934665603ull;

static void hmix(const void *p, size_t n) {
    const unsigned char *b = (const unsigned char *)p;
    for (size_t i = 0; i < n; i++) {
        g_traj ^= b[i];
        g_traj *= 1099511628211ull;
    }
}
static void hmix_f(float v) { hmix(&v, 4); }
static void hmix_i(int v) { hmix(&v, 4); }
static void hmix_state(const BtState &s, int env, int step) {
    hmix_f(s.hp);
    hmix_f(s.max_hp);
    hmix_f(s.px);
    hmix_f(s.py);
    hmix_f(s.materials);
    hmix_f(s.xp);
    hmix_f(s.dmg_taken);
    hmix_f(s.episode_return);
    hmix_f(s.time_left);
    hmix_f(s.wpn_cd[0]);
    hmix_f(s.wpn_melee_rot[0]);
    hmix_i(s.level);
    hmix_i(s.wave);
    hmix_i(s.ticks);
    hmix_i(s.kills);
    hmix_i(s.ecount);
    hmix_i(s.phase);
    hmix_i((int)s.lvl_offers[0]);
    hmix_i(s.wpn_count);
    hmix_i(env);
    hmix_i(step);
    hmix(&s.rng.state, sizeof(s.rng.state));
    hmix(&s.log.n, sizeof(s.log.n));
}

