__global__ void k_sin(const float *x, float *o, int n) {
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i < n) o[i] = bt_mc_sinf(x[i]);
}
__global__ void k_cos(const float *x, float *o, int n) {
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i < n) o[i] = bt_mc_cosf(x[i]);
}
__global__ void k_atan2(const float *y, const float *x, float *o, int n) {
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i < n) o[i] = bt_mc_atan2f(y[i], x[i]);
}
__global__ void k_sqrt(const float *x, float *o, int n) {
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i < n) o[i] = bt_mc_sqrtf(x[i]);
}

// Scalar libm calls through volatile pointers: the compiler must not swap them
// for its vectorized libmvec variants, because the CPU environment links a
// plain scalar call to these symbols.
static float (*volatile vp_sinf)(float) = sinf;
static float (*volatile vp_cosf)(float) = cosf;
static float (*volatile vp_sqrtf)(float) = sqrtf;
static float (*volatile vp_atan2f)(float, float) = atan2f;

static unsigned long long g_rng = 88172645463325252ull;
static unsigned long long xrand() {
    g_rng ^= g_rng << 13;
    g_rng ^= g_rng >> 7;
    g_rng ^= g_rng << 17;
    return g_rng;
}
static float u2f(unsigned int b) {
    float f;
    std::memcpy(&f, &b, 4);
    return f;
}

// ---------------------------------------------------------------------------
int main(int argc, char **argv) {
    (void)argc;
    (void)argv;

    const long MATH_SAMPLES = getenv("BT_MATH_SAMPLES") ? atol(getenv("BT_MATH_SAMPLES")) : 8000000;
    const int BENCH = getenv("BT_BENCH") ? atoi(getenv("BT_BENCH")) : 1;
    const int PARITY_STEPS = getenv("BT_PARITY_STEPS") ? atoi(getenv("BT_PARITY_STEPS")) : 20000;
    const int SKIP_TRAJECTORY = getenv("BT_SKIP_TRAJECTORY") ? 1 : 0;

    int dev = 0;
    cudaDeviceProp prop;
    ck(cudaGetDeviceProperties(&prop, dev), "device properties");
    size_t free_mem = 0, total_mem = 0;
    ck(cudaMemGetInfo(&free_mem, &total_mem), "mem info");
    std::printf("device: %s  sm_%d%d  %d SMs  %d threads/SM  %.2f GB free of %.2f GB\n", prop.name,
                prop.major, prop.minor, prop.multiProcessorCount, prop.maxThreadsPerMultiProcessor,
                free_mem / 1073741824.0, total_mem / 1073741824.0);
    std::printf("BT_OBS_SIZE=%d BT_ACTIONS=%d sizeof(BtState)=%zu sizeof(Env)=%zu (%.2f MiB/env)\n",
                BT_OBS_SIZE, BT_ACTIONS, sizeof(BtState), sizeof(Env), sizeof(Env) / 1048576.0);

    /* Focused real-wrapper kernel microbenchmark. Both layout modes execute
     * exactly the same Demon/endless states and action schedule; only puf_step
     * is timed, excluding initialization, H2D actions and snapshot packing.
     * BT_CUDA_LAYOUT_PROFILE=1 counts actual subscripts (not a speed run). */
    if (getenv("BT_LAYOUT_BENCH")) {
        int n = getenv("BT_LAYOUT_ENVS") ? atoi(getenv("BT_LAYOUT_ENVS")) : 4096;
        int ticks = getenv("BT_LAYOUT_TICKS") ? atoi(getenv("BT_LAYOUT_TICKS")) : 2000;
        require(n > 0 && ticks > 0, "positive layout benchmark dimensions");
        Batch b(n, 0, 1, "demon", "weapon_ghost_scepter_1", 1, 0, 0, 0);
        std::vector<int> actions(n);
        std::vector<cudaEvent_t> events((size_t)ticks * 2);
        for (cudaEvent_t& ev : events) ck(cudaEventCreate(&ev), "layout event");
        bt_gpu_layout_profile_reset();
        for (int t = 0; t < ticks; t++) {
            for (int e = 0; e < n; e++) actions[e] = action_for(t, e);
            b.set_actions(actions.data());
            ck(cudaEventRecord(events[2 * t]), "layout event start");
            puf_step(b.envs_d);
            ck(cudaEventRecord(events[2 * t + 1]), "layout event end");
        }
        ck(cudaDeviceSynchronize(), "layout benchmark sync");
        double total_ms = 0;
        for (int t = 0; t < ticks; t++) {
            float ms = 0;
            ck(cudaEventElapsedTime(&ms, events[2 * t], events[2 * t + 1]), "layout elapsed");
            total_ms += ms;
        }
        for (cudaEvent_t ev : events) cudaEventDestroy(ev);
        printf("layout_kernel envs=%d ticks=%d total_ms=%.6f ms_per_tick=%.6f steps_per_second=%.3f\n",
            n, ticks, total_ms, total_ms / ticks, (double)n * ticks * 1000 / total_ms);
        bt_gpu_layout_profile_report();
        return 0;
    }

    // Env.log must alias BtState.log at offset 0: the trainer's device log
    // reduce sums envs[i].log for the first total_agents/num_agents entries.
    static_assert(offsetof(Env, log) == 0, "Env.log must sit at offset 0");
    static_assert(offsetof(Env, state.log) == 0, "BtState.log must sit at offset 0");
    static_assert(sizeof(obs_t) == sizeof(float), "obs_t must be float32");

    init_coverage();

    const int ZONE = 0;
    const int SHOP_STEPS = 1;

    // ---- profile ids resolve on the host (the create path's input) ---------
    require(bt_character_id_from_name("bull") == BT_CHARACTER_BULL, "character token bull");
    require(bt_character_id_from_name("knight") == BT_CHARACTER_KNIGHT, "character token knight");
    require(bt_character_id_from_name("demon") == BT_CHARACTER_DEMON, "character token demon");
    require(bt_character_id_from_name(NULL) == BT_CHARACTER_BULL, "unknown character falls back to Bull");
    require(bt_weapon_id_from_name("weapon_hatchet_2") != BT_WEAPON_NONE, "weapon token hatchet");
    require(bt_weapon_id_from_name("weapon_ghost_scepter_1") != BT_WEAPON_NONE, "weapon token ghost scepter");
    require(bt_weapon_id_from_name("none") == BT_WEAPON_NONE, "weapon token none");

    // -----------------------------------------------------------------------
    // A. create path, and the log aliasing contract
    // -----------------------------------------------------------------------
    {
        const int N = 8;
        Batch b(N, ZONE, SHOP_STEPS, "bull", "none");
        Ref r(N, ZONE, SHOP_STEPS, BT_CHARACTER_BULL, BT_WEAPON_NONE);
        // Create contract, now identical to the CPU env (brotato.h puf_init ends
        // with bt_core_observe) and to Metal (brotato_metal.mm observes on
        // create): state field-by-field AND the observations, with rewards and
        // terminals zeroed.
        b.pull_all_envs();
        size_t pad = 0;
        for (int i = 0; i < N; i++) require_state_equal(b, r, i, &pad, -1, "create");
#if BT_ENV_HAS_ACTION_MASK
        std::string bad_create = compare_batch(b, r);
        if (!bad_create.empty()) fail("create: CPU/CUDA parity: " + bad_create);
        std::printf("A. create: %d envs initialised on the device match the host bt_core_init state, "
                    "every field (padding bytes differing: %zu) with obs/rew/term and the action mask "
                    "written by create\n", N, pad);
#else
        std::printf("A. create: %d envs initialised on the device match the host bt_core_init state, "
                    "every field (padding bytes differing: %zu); this brotato.cu revision does not write "
                    "obs/rew/term at create (pending landing) so they are checked after the step below\n",
                    N, pad);
#endif

        // One full-batch step from that fresh state: obs, reward and terminal
        // must now match the host, and every env must be independent.
        {
            std::vector<int> acts(N);
            for (int i = 0; i < N; i++) acts[i] = action_for(1, i);
            b.set_actions(acts.data());
            for (int i = 0; i < N; i++) r.step(i, acts[i]);
            b.step();
            b.pull_rewards();
            std::string bad = compare_batch(b, r);
            if (!bad.empty()) fail("step: CPU/CUDA parity: " + bad);
            std::printf("A. step: full-batch step wrote obs/reward/terminal identical to the host\n");
        }

        // reset: fresh episode, observations rewritten, rewards/terminals zeroed,
        // accumulated log preserved.
        std::vector<float> log_before((size_t)N * 5);
        for (int i = 0; i < N; i++) {
            log_before[(size_t)i * 5 + 0] = r.s[i].log.perf;
            log_before[(size_t)i * 5 + 1] = r.s[i].log.score;
            log_before[(size_t)i * 5 + 2] = r.s[i].log.episode_return;
            log_before[(size_t)i * 5 + 3] = r.s[i].log.episode_length;
            log_before[(size_t)i * 5 + 4] = r.s[i].log.n;
        }
        b.reset();
        r.reset(true);
        std::string bad = compare_batch(b, r);
        if (!bad.empty()) fail("reset: CPU/CUDA parity: " + bad);
        for (int i = 0; i < N; i++) {
            b.pull_env(i);
            const BtState &s = b.env(i)->state;
            if (s.log.n != log_before[(size_t)i * 5 + 4]) fail("reset must preserve log.n", i);
            if (s.ticks != 0) fail("reset must zero ticks", i);
            if (s.wave != 1) fail("reset must restart at wave 1", i);
            if (b.rew_h[i] != 0.0f || b.term_h[i] != 0.0f) fail("reset must zero reward/terminal", i);
        }
        require_state_equal(b, r, 0, &pad, -1, "reset");
        std::printf("A. reset: host bt_core_reset/observe reproduced exactly, log preserved, "
                    "rewards/terminals zeroed\n");

        // puf_log copies this env's accumulated Log into the dict.
        {
            Dict out;
            std::memset(&out, 0, sizeof(out));
            struct Log log_copy = b.env(0)->log;
            puf_log(&log_copy, &out);
            require(dict_get(&out, "episode_length") == (double)b.env(0)->state.log.episode_length,
                    "puf_log must publish episode_length");
            require(dict_get(&out, "n") == (double)b.env(0)->state.log.n, "puf_log must publish n");
            require(dict_get(&out, "perf") == (double)b.env(0)->state.log.perf, "puf_log must publish perf");
            std::printf("A. log: Env.log aliases BtState.log at offset 0 and puf_log publishes it\n");
        }

        // After puf_close the wrapper's batch is empty and step/reset must be
        // no-ops rather than launching a zero-block grid.
        {
            Batch tmp(4, ZONE, SHOP_STEPS, "bull", "none");
            Env *dead = tmp.envs_d;
            tmp.envs_d = nullptr;      // do not close twice; free buffers via the dtor
            puf_close(dead);
            puf_step(dead);
            puf_reset(dead);
            ck(cudaDeviceSynchronize(), "closed-batch no-op");
            std::printf("A. closed batch: step/reset are no-ops\n");
        }
    }

    if (!SKIP_TRAJECTORY) {
        // -------------------------------------------------------------------
        // C. CPU vs CUDA, strict, per step, Bull
        // -------------------------------------------------------------------
        struct Cover {
            bool combat = false, shop = false, levelup = false, terminal = false;
            int terminals = 0;
            // How much of each phase the profile actually sampled.  combat and
            // terminal are required per profile; shop/level-up are accumulated
            // across the profile set AND required on the wave_ovr Demon profile.
            int shop_ticks = 0, levelup_ticks = 0;
            bool lock_seen = false;   // a shop offer was actually locked (lock profile)
        };
        // Phase-coverage policy: combat and terminal are required of EVERY profile;
        // shop and level-up are accumulated here across the whole profile set (the
        // Demon dies before any 20 s wave ends, so its campaign/endless profiles can
        // never reach either) and additionally hard-required on the wave_ovr Demon
        // profile, which is the run that exercises the Demon's HP-currency shop and
        // its level-up offers on the device.
        Cover all_cov;
        auto run_parity = [&](const char *tag, const char *character, const char *weapon,
                              unsigned short ch_id, unsigned short wp_id, int endless,
                              int max_steps, int audio_rng, int start_wave, int particles_rng,
                              float wave_ovr = 0.0f, int unlock_all = 1, int invulnerable = 0,
                              int shop_lock = 0, int allow_no_terminal = 0) -> Cover {
            const int N = 32;
            Batch b(N, ZONE, SHOP_STEPS, character, weapon, endless, audio_rng, start_wave, particles_rng,
                    0, wave_ovr, unlock_all, invulnerable);
            Ref r(N, ZONE, SHOP_STEPS, ch_id, wp_id, endless, audio_rng, start_wave, particles_rng,
                  character, weapon, wave_ovr, unlock_all, invulnerable);
            Cover cov;
            std::vector<int> acts(N), shop_tick(N, 0);   // shop_tick: lock schedule position
            const int STATE_ONE_EVERY = 8;    // envs 0..3 every 8 steps
            const int STATE_ALL_EVERY = 512;  // every env every 512 steps
            size_t pad_total = 0;
            int step = 0;
            auto t0 = std::chrono::steady_clock::now();
            for (; step < max_steps; step++) {
                g_step = step;
                if (shop_lock) {
                    // Locked-shop schedule (see BT_SHOP_LOCK_*): one lock action per
                    // shop tick until the parity's set is locked, then reroll forever.
                    for (int i = 0; i < N; i++) {
                        if (r.s[i].phase == 1) {
                            int t = shop_tick[i];
                            acts[i] = (i & 1) ? BT_SHOP_LOCK_SPARSE[t < 4 ? t : 4]
                                              : BT_SHOP_LOCK_FULL[t < 4 ? t : 4];
                            if (t < 4) shop_tick[i] = t + 1;
                        } else {
                            acts[i] = action_for(step, i);
                            shop_tick[i] = 0;
                        }
                    }
                } else {
                    for (int i = 0; i < N; i++) acts[i] = action_for(step, i);
                }
                for (int i = 0; i < N; i++) {
                    if (r.s[i].phase == 0 && r.s[i].ticks > 0) cov.combat = true;
                    if (r.s[i].phase == 1) { cov.shop = true; cov.shop_ticks++; }
                    if (r.s[i].lvl_offers[0] != 0) { cov.levelup = true; cov.levelup_ticks++; }
                    for (int k = 0; k < 4; k++)
                        if (r.s[i].shop_locked[k] != 0) cov.lock_seen = true;
                    r.step(i, acts[i]);
                    if (r.term[i] > 0.5f) {
                        cov.terminal = true;
                        cov.terminals++;
                    }
                }
                b.set_actions(acts.data());
                b.step();
                b.pull_rewards();
                std::string bad = compare_batch(b, r);
                if (!bad.empty()) fail(std::string(tag) + " CPU/CUDA parity broke: " + bad);
                // The all-envs pass must be tested FIRST: every multiple of
                // STATE_ALL_EVERY is also a multiple of STATE_ONE_EVERY, so the
                // previous `else if` order made the wide comparison dead code and
                // the summary line's "all N envs every 512 steps" a lie.
                if (step % STATE_ALL_EVERY == 0) {
                    b.pull_all_envs();
                    for (int i = 0; i < N; i++) require_state_equal(b, r, i, &pad_total, step, tag);
                } else if (step % STATE_ONE_EVERY == 0) {
                    for (int i = 0; i < 4; i++) b.pull_env(i);
                    for (int i = 0; i < 4; i++) require_state_equal(b, r, i, &pad_total, step, tag);
                }
                if (cov.combat && cov.shop && cov.levelup && cov.terminal) {
                    step++;
                    break;
                }
                if (step % 2000 == 1999) {
                    double el = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
                    std::printf("   ... %s step %d (%.1fs, %.0f env-steps/s host+device): combat %d shop %d "
                                "levelup %d terminal %d\n", tag, step + 1, el, (step + 1) * (double)N / el,
                                (int)cov.combat, cov.shop_ticks, cov.levelup_ticks, cov.terminals);
                    std::fflush(stdout);
                }
            }
            b.pull_all_envs();
            for (int i = 0; i < N; i++) require_state_equal(b, r, i, &pad_total, step, tag);
            b.pull_obs();
            std::string bad = compare_batch(b, r);
            if (!bad.empty()) fail(std::string(tag) + " final CPU/CUDA parity: " + bad);
            if (endless) {
                b.pull_all_envs();
                for (int i = 0; i < N; i++) {
                    require(b.env(i)->state.endless == 1, "endless flag must reach the device state", i);
                    require(r.s[i].endless == 1, "host reference must carry the endless flag", i);
                }
            }
            if (!audio_rng) {
                // The flag gates *draws* (brotato_*_audio.h skips exactly the
                // source's audio-RNG draws when 0), so a flag that did not reach
                // the device state would show up as an RNG divergence within a
                // few steps -- but assert it directly too.
                b.pull_all_envs();
                for (int i = 0; i < N; i++) {
                    require(b.env(i)->state.audio_rng == 0, "audio_rng=0 must reach the device state", i);
                    require(r.s[i].audio_rng == 0, "host reference must carry audio_rng=0", i);
                }
            }
            if (start_wave >= 1) {
                // The launch used to pass the init kernel's (audio_rng, start_wave)
                // in the wrong order, which silently turned a configured
                // start_wave into audio_rng and vice versa -- assert both fields
                // so a swap cannot hide behind a later divergence.
                b.pull_all_envs();
                for (int i = 0; i < N; i++) {
                    require(b.env(i)->state.start_wave == (unsigned short)start_wave,
                            "start_wave must reach the device state", i);
                    require(r.s[i].start_wave == (unsigned short)start_wave,
                            "host reference must carry start_wave", i);
                }
            }
            if (!particles_rng) {
                // Same idea as audio_rng: the key gates draws, and it has no
                // bt_core_init parameter (both wrappers write the state field
                // after init), so assert it directly as well.
                b.pull_all_envs();
                for (int i = 0; i < N; i++) {
                    require(b.env(i)->state.particles_rng == 0,
                            "particles_rng=0 must reach the device state", i);
                    require(r.s[i].particles_rng == 0, "host reference must carry particles_rng=0", i);
                }
            }
            if (!unlock_all) {
                // The loot-pool profile has no bt_core_init parameter either: the
                // init kernel writes lock_default_items (brotato.cu:290) and the
                // host wrapper writes it too (brotato.h:522), and bt_core_reset
                // preserves it, so a locked-pool run must carry it on both sides
                // through every reset.  It gates the loot roll (brotato_loot.h:449).
                b.pull_all_envs();
                for (int i = 0; i < N; i++) {
                    require(b.env(i)->state.lock_default_items == 1,
                            "unlock_all=0 must reach the device state as lock_default_items == 1", i);
                    require(r.s[i].lock_default_items == 1,
                            "host reference must carry the locked-pool flag", i);
                }
            }
            if (wave_ovr > 0.0f) {
                // The replay override must reach the device state and must survive
                // the device's own resets (bt_core_reset preserves wave_ovr), so
                // both backends re-enter the same overridden wave duration -- this
                // is the field the parity path would otherwise never exercise.
                b.pull_all_envs();
                for (int i = 0; i < N; i++) {
                    require(b.env(i)->state.wave_ovr == wave_ovr,
                            "wave_ovr must reach the device state", i);
                    require(r.s[i].wave_ovr == wave_ovr, "host reference must carry wave_ovr", i);
                    require(b.env(i)->state.wave_duration == r.s[i].wave_duration,
                            "both backends must re-enter the overridden wave duration", i);
                }
            }
            if (invulnerable) {
                // DebugService.invulnerable has no bt_core_init parameter: both
                // wrappers write the state field after init (brotato.h:508,
                // brotato.cu:282) and bt_core_reset does not clear it.
                b.pull_all_envs();
                for (int i = 0; i < N; i++) {
                    require(b.env(i)->state.invulnerable == 1,
                            "invulnerable=1 must reach the device state", i);
                    require(r.s[i].invulnerable == 1, "host reference must carry invulnerable", i);
                }
            }
            require(cov.combat, "coverage: no combat phase observed");
            if (allow_no_terminal) {
                // An invulnerable endless deep-start profile cannot end an episode:
                // the player cannot die and endless has no wave-20 win, so the only
                // thing it must still reach is the shop (whose LOCK/REROLL path is
                // the point of the profile).  Every other profile requires terminal.
                require(cov.shop, "the invulnerable deep profile must reach the shop");
            } else {
                require(cov.terminal, "coverage: no episode termination observed");
            }
            if (shop_lock)
                require(cov.lock_seen, "the locked-shop profile must actually lock shop offers");
            all_cov.shop = all_cov.shop || cov.shop;
            all_cov.levelup = all_cov.levelup || cov.levelup;
            all_cov.shop_ticks += cov.shop_ticks;
            all_cov.levelup_ticks += cov.levelup_ticks;
            all_cov.terminals += cov.terminals;
            std::printf("C. %s: %d steps x %d envs bit-exact (obs+reward+terminal every step, every "
                        "BtState field on envs 0..3 every %d steps and all %d envs every %d steps); "
                        "coverage: combat+terminal asserted here, shop %d / level-up %d tick samples "
                        "(asserted across the profile set and per profile on the wave_ovr Demon run); "
                        "%d terminals, padding bytes differing %zu\n",
                        tag, step, N, STATE_ONE_EVERY, N, STATE_ALL_EVERY, cov.shop_ticks,
                        cov.levelup_ticks, cov.terminals, pad_total);
            return cov;
        };

        // Demon-first (project directive): the Demon + ghost scepter profiles are
        // the ones every downstream gate replays, so they run before the other
        // two and a regression in one of those cannot hide behind an unrelated
        // Bull/Knight failure.  All profiles still run.  Argument tail is
        // (..., max_steps, audio_rng, start_wave, particles_rng).
        run_parity("demon+ghost_scepter_1", "demon", "weapon_ghost_scepter_1", BT_CHARACTER_DEMON,
                   (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"), 0, PARITY_STEPS, 1, 0, 1);
        // The Demon's shop is the HP-currency one and is only reachable at a wave
        // end.  Every 20 s-wave Demon profile above dies in ~600-860 ticks
        // (wave 1 is 1200 ticks), so none of them ever reaches it -- measured on
        // the host for hold / harness-schedule / move-only policies, which is why
        // the shop/level-up requirements are not per profile any more.  This
        // profile boots the SAME character and weapon through the replay lane's
        // wave-duration override so waves DO end before the Demon dies, and the
        // two phases are then required ON THIS PROFILE, on both backends: it is
        // the run that proves the Demon shop/level-up path is bit-exact on the
        // device, which is exactly what the GPU env has to serve downstream.
        {
            Cover cov_ovr = run_parity("demon+ghost_scepter_1 wave_ovr=2 (replay lane)", "demon",
                                       "weapon_ghost_scepter_1", BT_CHARACTER_DEMON,
                                       (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"),
                                       0, PARITY_STEPS, 1, 0, 1, 2.0f);
            require(cov_ovr.shop, "the wave_ovr Demon profile must reach the shop phase (HP currency)");
            require(cov_ovr.levelup, "the wave_ovr Demon profile must reach a level-up offer");
        }
        // unlock_all = 0 (the fresh-save LOCKED loot pool) on the same replay lane:
        // the locked branch of the loot roll (brotato_loot.h:449) changes which
        // items the shop draws, so it must be compared with the shop reached, on
        // both backends, with the flag asserted in the device state.
        {
            Cover cov_lock = run_parity("demon+ghost_scepter_1 wave_ovr=2 unlock_all=0 (locked pool)",
                                        "demon", "weapon_ghost_scepter_1", BT_CHARACTER_DEMON,
                                        (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"),
                                        0, PARITY_STEPS, 1, 0, 1, 2.0f, 0);
            require(cov_lock.shop, "the unlock_all=0 profile must reach the shop (the locked loot roll)");
        }
        // Deep immortal profile with a LOCKED shop: the device-only OOB write in
        // bt_progress_roll_shop's locked-offer snapshot (compute-sanitizer: "Invalid
        // __local__ write of size 1", addressed by the running match counter) only
        // fires when the shop holds locked offers and is rerolled, and no host-side
        // build reproduces it (the CPU core is clean under ASan, see
        // tests/test_brotato_shop_lock.cpp).  start_wave 40 + endless + invulnerable
        // keeps the demon alive out of the shop at a deep wave, the wave_ovr replay
        // lane ends a wave every 2 s (~120 ticks) so the shop keeps reopening, and
        // the shop schedule walks the LOCK actions 21..24 and REROLL (4): even envs
        // lock all four offers (the fully locked 4-slot shop), odd envs lock offers
        // 0 and 2 and reroll with them held (see BT_SHOP_LOCK_*).  No terminal is
        // required (invulnerable endless cannot end an episode); the shop, the lock
        // effect and the full state parity are.
        {
            (void)run_parity("demon+ghost_scepter_1 start_wave=40 endless invulnerable wave_ovr=2 lock+reroll",
                             "demon", "weapon_ghost_scepter_1", BT_CHARACTER_DEMON,
                             (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"),
                             /*endless*/ 1, PARITY_STEPS, /*audio_rng*/ 1, /*start_wave*/ 40,
                             /*particles_rng*/ 1, /*wave_ovr*/ 2.0f, /*unlock_all*/ 1,
                             /*invulnerable*/ 1, /*shop_lock*/ 1, /*allow_no_terminal*/ 1);
        }
        // Endless (wave 21+) is a distinct code path in bt_core_step's wave-20
        // branch and a state flag that bt_core_reset must not clear, so it gets
        // its own CPU-vs-CUDA run rather than a note.
        run_parity("demon+ghost_scepter_1 ENDLESS", "demon", "weapon_ghost_scepter_1", BT_CHARACTER_DEMON,
                   (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"), 1, PARITY_STEPS, 1, 0, 1);
        // audio_rng=0 is the RL bridge's audiovisual neutralization: the shared
        // core then skips exactly the audio-RNG draws (brotato_birth_audio.h,
        // brotato_weapon_audio.h, brotato_combat_audio.h), so the Utils/main
        // streams shift from that point on.  A backend that ignores the key --
        // or gates a different set of draws -- desynchronises every later pick,
        // which is a real CPU-vs-CUDA divergence, so it gets its own run.
        run_parity("demon+ghost_scepter_1 audio_rng=0", "demon", "weapon_ghost_scepter_1",
                   BT_CHARACTER_DEMON, (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"),
                   0, PARITY_STEPS, 0, 0, 1);
        // particles_rng=0: the same shape of option for the particles RNG
        // (default 1), written by both wrappers into state.particles_rng after
        // init (no bt_core_init parameter), so a CUDA init-kernel argument that
        // is dropped or mis-indexed shows up as an immediate divergence.
        run_parity("demon+ghost_scepter_1 particles_rng=0", "demon", "weapon_ghost_scepter_1",
                   BT_CHARACTER_DEMON, (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"),
                   0, PARITY_STEPS, 1, 0, 0);
        // Optional deep-start: start_wave=20 boots the run at the enemy cap, as
        // the SPS benchmarks and replay gates use.  It must reach the device
        // state, not be dropped or swapped with the neighbouring init-kernel
        // argument.
        run_parity("demon+ghost_scepter_1 start_wave=20", "demon", "weapon_ghost_scepter_1",
                   BT_CHARACTER_DEMON, (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"),
                   0, PARITY_STEPS, 1, 20, 1);
        // All three non-default optional keys at once: the device must apply
        // exactly audio_rng=0, particles_rng=0 and start_wave=20 -- this is the
        // case that catches an argument-order slip in the init-kernel launch.
        run_parity("demon+ghost_scepter_1 audio_rng=0 particles_rng=0 start_wave=20", "demon",
                   "weapon_ghost_scepter_1", BT_CHARACTER_DEMON,
                   (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"),
                   0, PARITY_STEPS, 0, 20, 0);
        // Endless with all three optional keys, the configuration the endless SPS
        // / replay gates actually run.
        run_parity("demon+ghost_scepter_1 ENDLESS audio_rng=0 particles_rng=0 start_wave=20", "demon",
                   "weapon_ghost_scepter_1", BT_CHARACTER_DEMON,
                   (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"),
                   1, PARITY_STEPS, 0, 20, 0);
        run_parity("bull+none", "bull", "none", BT_CHARACTER_BULL, BT_WEAPON_NONE, 0, PARITY_STEPS, 1, 0, 1);
        run_parity("knight+hatchet_2", "knight", "weapon_hatchet_2", BT_CHARACTER_KNIGHT,
                   (unsigned short)bt_weapon_id_from_name("weapon_hatchet_2"), 0, PARITY_STEPS, 1, 0, 1);
        // Shop and level-up are accumulated across the profile set: the Demon's
        // 20 s-wave profiles cannot reach either (see the wave_ovr profile above),
        // and the wave_ovr Demon profile already asserts them per profile, so a
        // failure here means no profile saw the phase at all.
        require(all_cov.shop, "coverage: no shop phase observed in any profile");
        require(all_cov.levelup, "coverage: no level-up offer observed in any profile");
        std::printf("C. phase coverage across the Demon-first profile set: shop %d / level-up %d tick samples\n",
                    all_cov.shop_ticks, all_cov.levelup_ticks);

        // -------------------------------------------------------------------
        // H. experimental lane scheduler (warp_step) and the wide mask row
        // -------------------------------------------------------------------
#if defined(BTFW_EXPERIMENTAL_LANE_SCHED)
        {
            // Drive the REAL wiring the warp_step flag selects -- puf_vec_create
            // with warp_step=1, then puf_reset/puf_step on the batch binding --
            // instead of hand-launching btfw_init_kernel/btfw_step_kernel, and
            // require a terminal tick: without one the in-kernel
            // bt_core_add_log + bt_core_reset + bt_core_observe sequence (the
            // only in-kernel episode reset, and what puf_reset's contract leans
            // on) is never exercised, so a "PASS" would prove nothing about it.
            const int N = 32;
            // The gate is only meaningful if the warp path is actually armed:
            // btfw_scratch_bytes() is 0 in a build without the physics backend, in
            // which case puf_vec_create forces use_warp back to 0 and the block
            // below would silently re-run the plain serial kernel.
            require(btfw_scratch_bytes() > 0,
                    "layer H needs a lane-scheduler build WITH the physics backend (btfw_scratch_bytes() > 0)");
            Batch b(N, ZONE, SHOP_STEPS, "demon", "weapon_ghost_scepter_1", 0, 1, 0, 1, 1);
            require(g_gpu.use_warp == 1,
                    "puf_vec_create must arm the warp path for warp_step=1 (not fall back to the serial kernel)");
            Ref r(N, ZONE, SHOP_STEPS, BT_CHARACTER_DEMON,
                  (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"), 0, 1, 0, 1);
            b.reset();
            r.reset(true);
            std::vector<int> acts(N);
            bool term_seen = false;
            int used = 0;
            for (; used < PARITY_STEPS; used++) {
                for (int i = 0; i < N; i++) acts[i] = action_for(used, i);
                b.set_actions(acts.data());
                b.step();
                b.pull_rewards();
                for (int i = 0; i < N; i++) r.step(i, acts[i]);
                std::string bad = compare_batch(b, r);
                if (!bad.empty()) fail("H warp_step=1 CPU/CUDA parity broke: " + bad);
                for (int i = 0; i < N; i++) if (b.term_h[i] > 0.5f) term_seen = true;
                if (term_seen) { used++; break; }
            }
            b.pull_all_envs();
            size_t pad = 0;
            for (int i = 0; i < N; i++) require_state_equal(b, r, i, &pad, used, "warp_step end");
            require(term_seen, "warp_step=1: no terminal tick through puf_vec_create/puf_step "
                               "(raise BT_PARITY_STEPS; without a terminal the autoreset path is untested)");
            std::printf("H. warp_step=1 via puf_vec_create/puf_reset/puf_step: bit-exact over %d steps x %d envs "
                        "with a terminal tick reached\n", used, N);
            // The warp run armed the DEVICE-WIDE dispatch mode: puf_vec_create
            // wrote btf_phys_backend = 1 and btf_group_bp = 32 ("one warp per env,
            // lane 0 owns every serial span").  Nothing restores it -- a later
            // create only re-arms when IT is asked for warp_step=1 -- and the
            // plain one-thread-per-env kernel needs btf_group_bp <= 1, because
            // BT_SERIAL wraps its span in `if (BTF_IS_LEADER())`
            // (brotato_gpu_framework.cuh:282) and BTF_IS_LEADER() with bp == 32 is
            // `(threadIdx.x & 31) == 0`.  Left armed, every later plain batch runs
            // the serial spans of bt_core_step on lane 0 ONLY: layer D caught
            // exactly that -- env 0 stepped, envs 1..3 kept their create-time
            // observations, so obs[66] was the fresh wave clock (0.999166667)
            // against the host's one tick (0.998333335).  Restore the serial mode
            // (bt_core_init/bt_core_reset are not span-guarded, which is why the
            // create and reset comparisons above stayed clean).
            {
                int serial_backend = 0, serial_group = 1;
                ck(cudaMemcpyToSymbol(btf_phys_backend, &serial_backend, sizeof(int)),
                   "restore serial physics backend");
                ck(cudaMemcpyToSymbol(btf_group_bp, &serial_group, sizeof(int)),
                   "restore serial dispatch mode (group bp)");
            }
        }
#endif
        {
            // A mask row WIDER than BT_ACTIONS (the trainer may reserve ids):
            // the live head must match bt_action_mask and the reserved tail must
            // be zero-filled.  The buffer is poisoned first so a writer that
            // stops at BT_ACTIONS is caught.
            const int N = 4, WIDE = BT_ACTIONS + 8;
            Batch b(N, ZONE, SHOP_STEPS, "demon", "weapon_ghost_scepter_1");
            Ref r(N, ZONE, SHOP_STEPS, BT_CHARACTER_DEMON,
                  (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"));
            unsigned char *wide = nullptr;
            ck(cudaMalloc(&wide, (size_t)N * WIDE), "wide mask malloc");
            ck(cudaMemset(wide, 0xAB, (size_t)N * WIDE), "poison wide mask");
            puf_bind_action_mask(wide, WIDE);
            b.reset();
            r.reset(false);
            std::vector<unsigned char> h((size_t)N * WIDE);
            ck(cudaMemcpy(h.data(), wide, h.size(), cudaMemcpyDeviceToHost), "D2H wide mask");
            for (int i = 0; i < N; i++) {
                unsigned char want[BT_ACTIONS];
                bt_action_mask(&r.s[i], want);
                for (int a = 0; a < BT_ACTIONS; a++)
                    require(h[(size_t)i * WIDE + a] == want[a], "wide mask head must match bt_action_mask", i);
                for (int a = BT_ACTIONS; a < WIDE; a++)
                    require(h[(size_t)i * WIDE + a] == 0, "wide mask tail must be zero-filled", i);
            }
            puf_bind_action_mask(b.mask_d, BT_ACTIONS);   // restore for later layers
            ck(cudaFree(wide), "wide mask free");
            std::printf("H. mask row wider than BT_ACTIONS (%d): head matches bt_action_mask, poisoned tail zero-filled\n",
                        WIDE);
        }

        // -------------------------------------------------------------------
        // B. determinism
        //
        // The CUDA wrapper keeps ONE batch binding (puf_step ignores its Env*
        // argument and steps g_gpu.envs, mirroring the trainer's
        // num_buffers == 1 rule), so two batches cannot be interleaved. Each
        // configuration therefore runs the same schedule on its own and the
        // per-step digests must be equal.
        // -------------------------------------------------------------------
        {
            const int N = 16, STEPS = 400;
            auto digest_run = [&](const char *tag) {
                Batch b(N, ZONE, SHOP_STEPS, "demon", "weapon_ghost_scepter_1");
                unsigned long long h = 1469598103934665603ull;
                std::vector<int> acts(N);
                for (int s = 0; s < STEPS; s++) {
                    for (int i = 0; i < N; i++) acts[i] = action_for(s + 3, i);
                    b.set_actions(acts.data());
                    b.step();
                    b.pull_obs();
                    g_traj = h;
                    hmix(b.obs_h.data(), b.obs_h.size() * sizeof(float));
                    h = g_traj;
                }
                std::printf("      %s digest %016llx\n", tag, h);
                return h;
            };
            unsigned long long h1 = digest_run("run 1");
            unsigned long long h2 = digest_run("run 2");
            require(h1 == h2, "two identically configured batches must produce identical trajectories");
            std::printf("B. determinism: two independent runs matched bit-exactly over %d steps x %d envs\n",
                        STEPS, N);
        }

        // -------------------------------------------------------------------
        // D. profile config reaches the kernel
        // -------------------------------------------------------------------
        {
            const int N = 4;
            struct P {
                const char *chr, *wpn;
                unsigned short cid, wid;
            } profs[] = {
                {"bull", "none", BT_CHARACTER_BULL, BT_WEAPON_NONE},
                {"knight", "weapon_hatchet_2", BT_CHARACTER_KNIGHT, 0},
                {"demon", "weapon_ghost_scepter_1", BT_CHARACTER_DEMON, 0},
            };
            Batch bull(N, ZONE, SHOP_STEPS, "bull", "none");
            {
                std::vector<int> z(N, 0);
                bull.set_actions(z.data());
                bull.step();
                bull.pull_obs();
            }
            for (P &p : profs) {
                if (p.wid == 0 && std::strcmp(p.wpn, "none") != 0)
                    p.wid = (unsigned short)bt_weapon_id_from_name(p.wpn);
                Batch b(N, ZONE, SHOP_STEPS, p.chr, p.wpn);
                Ref r(N, ZONE, SHOP_STEPS, p.cid, p.wid);
                b.pull_all_envs();
                for (int i = 0; i < N; i++) {
                    require_state_equal(b, r, i, nullptr, -1, "profile create");
                    const BtState &s = b.env(i)->state;
                    require(s.character == p.cid, "kernel must receive character", i);
                    require(s.starting_weapon == p.wid, "kernel must receive starting weapon", i);
                }
                // obs is written by the first step (or by reset)
                std::vector<int> z(N, 0);
                b.set_actions(z.data());
                for (int i = 0; i < N; i++) r.step(i, 0);
                b.step();
                b.pull_rewards();
                std::string bad = compare_batch(b, r);
                if (!bad.empty()) fail(std::string("profile ") + p.chr + ": initial parity: " + bad);
                bool differs = false;
                for (int j = 0; j < BT_OBS_SIZE; j++)
                    if (!feq(b.ob(0)[j], bull.ob(0)[j])) differs = true;
                if (std::strcmp(p.chr, "bull") != 0) require(differs, "profile must change the initial state");
                std::printf("D. profile %s + %s: ids reached the kernel, initial state matches the host, "
                            "%s\n", p.chr, p.wpn, differs ? "differs from Bull" : "is Bull");
            }
        }
    }

    // -----------------------------------------------------------------------
    // E. the device math port against this host's libm
    // -----------------------------------------------------------------------
    {
        const long N = MATH_SAMPLES;
        std::vector<unsigned int> hx((size_t)N), hy((size_t)N);
        for (long i = 0; i < N; i++) {
            unsigned int b = (unsigned int)(xrand() >> 32);
            unsigned int mode = (unsigned int)(xrand() % 4);
            if (mode == 1) {
                // |x| in [0, 128) radians: the rotations, aim angles and spreads
                // the core actually produces.
                b = (b & 0x807fffffu) | ((unsigned int)(120 + xrand() % 8) << 23);
                if (xrand() & 1) b ^= 0x80000000u;
            } else if (mode == 2) {
                // the primary polynomial path, |x| in [2^-12, 1)
                b = (b & 0x807fffffu) | ((unsigned int)(115 + xrand() % 12) << 23);
                if (xrand() & 1) b ^= 0x80000000u;
            } else if (mode == 3) {
                // near multiples of pi/4, 1.0 and the tiny/denormal boundary
                double m = (double)(xrand() % 1000000) / 1000000.0;
                b = fbits((float)(m * 3.14159265358979323846));
                if (xrand() & 1) b ^= 0x80000000u;
            }
            hx[(size_t)i] = b;
            hy[(size_t)i] = (unsigned int)(xrand() >> 32);
        }
        float *dx = nullptr, *dy = nullptr, *dout = nullptr;
        float *hout = (float *)std::malloc((size_t)N * sizeof(float));
        ck(cudaMalloc(&dx, (size_t)N * 4), "cudaMalloc(math x)");
        ck(cudaMalloc(&dy, (size_t)N * 4), "cudaMalloc(math y)");
        ck(cudaMalloc(&dout, (size_t)N * 4), "cudaMalloc(math out)");
        ck(cudaMemcpy(dx, hx.data(), (size_t)N * 4, cudaMemcpyHostToDevice), "H2D math x");
        ck(cudaMemcpy(dy, hy.data(), (size_t)N * 4, cudaMemcpyHostToDevice), "H2D math y");
        const int th = 256;
        const unsigned bl = (unsigned)((N + th - 1) / th);
        struct Res {
            const char *name;
            long mismatch, nonfinite;
            float worst;
        };
        Res res[4] = {{"sinf", 0, 0, 0.0f}, {"cosf", 0, 0, 0.0f}, {"atan2f", 0, 0, 0.0f}, {"sqrtf", 0, 0, 0.0f}};
        for (int which = 0; which < 4; which++) {
            if (which == 0) k_sin<<<bl, th>>>(dx, dout, (int)N);
            else if (which == 1) k_cos<<<bl, th>>>(dx, dout, (int)N);
            else if (which == 2) k_atan2<<<bl, th>>>(dy, dx, dout, (int)N);
            else k_sqrt<<<bl, th>>>(dx, dout, (int)N);
            ck(cudaGetLastError(), "math kernel launch");
            ck(cudaDeviceSynchronize(), "math kernel");
            ck(cudaMemcpy(hout, dout, (size_t)N * 4, cudaMemcpyDeviceToHost), "D2H math out");
            for (long i = 0; i < N; i++) {
                float x = u2f(hx[(size_t)i]), y = u2f(hy[(size_t)i]);
                float want;
                if (which == 0) want = vp_sinf(x);
                else if (which == 1) want = vp_cosf(x);
                else if (which == 2) want = vp_atan2f(y, x);
                else want = vp_sqrtf(x);
                if (!feq(hout[i], want)) {
                    res[which].mismatch++;
                    if (!std::isfinite(x) || (which == 2 && !std::isfinite(y))) res[which].nonfinite++;
                    if (res[which].mismatch <= 3)
                        std::printf("   E mismatch %s: x=0x%08x y=0x%08x device=0x%08x libm=0x%08x\n",
                                    res[which].name, hx[(size_t)i], hy[(size_t)i], fbits(hout[i]), fbits(want));
                }
                float d = std::fabs(hout[i] - want);
                if (std::isfinite(d) && d > res[which].worst) res[which].worst = d;
            }
        }
        cudaFree(dx);
        cudaFree(dy);
        cudaFree(dout);
        std::free(hout);
        for (int i = 0; i < 4; i++) {
            std::printf("E. %-7s device vs host libm over %ld samples: %ld mismatches (%ld of them with a "
                        "non-finite argument), worst |diff| %.3g\n", res[i].name, N, res[i].mismatch,
                        res[i].nonfinite, res[i].worst);
            if (res[i].mismatch != 0) fail(std::string("device ") + res[i].name + " is not bit-exact with libm");
        }
    }

    // -----------------------------------------------------------------------
    // F. throughput, kernel cost and occupancy
    // -----------------------------------------------------------------------
    if (BENCH) {
        cudaFuncAttributes attr;
        ck(cudaFuncGetAttributes(&attr, (const void *)bt_gpu_step_kernel), "step kernel attributes");
        int blocks_per_sm = 0;
        ck(cudaOccupancyMaxActiveBlocksPerMultiprocessor(&blocks_per_sm, (const void *)bt_gpu_step_kernel,
                                                        BT_GPU_BLOCK, 0),
           "occupancy");
        std::printf("F. step kernel: %d registers/thread, %zu local bytes, %d max threads/block, "
                    "%d blocks/SM (%d threads/SM, %d warps/SM), %d SMs -> %d resident envs\n",
                    attr.numRegs, attr.localSizeBytes, attr.maxThreadsPerBlock, blocks_per_sm,
                    blocks_per_sm * BT_GPU_BLOCK, blocks_per_sm * BT_GPU_BLOCK / 32,
                    prop.multiProcessorCount, blocks_per_sm * BT_GPU_BLOCK * prop.multiProcessorCount);
        cudaFuncAttributes attr_r;
        ck(cudaFuncGetAttributes(&attr_r, (const void *)bt_gpu_reset_kernel), "reset kernel attributes");

        const int sizes[] = {128, 256, 512, 1024, 1536};
        for (int si = 0; si < 5; si++) {
            int n = sizes[si];
            size_t need = (size_t)n * sizeof(Env) + (size_t)n * BT_OBS_SIZE * sizeof(float) + 3 * n * 4;
            size_t fr = 0, tt = 0;
            ck(cudaMemGetInfo(&fr, &tt), "mem info");
            if (need > fr) {
                std::printf("F. n=%d needs %.2f GB, only %.2f GB free: skipped\n", n, need / 1073741824.0,
                            fr / 1073741824.0);
                continue;
            }
            Batch b(n, ZONE, SHOP_STEPS, "demon", "weapon_ghost_scepter_1");
            std::vector<int> acts(n);
            const int STEPS = 200;
            for (int i = 0; i < n; i++) acts[i] = action_for(0, i);
            b.set_actions(acts.data());
            for (int i = 0; i < 5; i++) b.step();     // warm-up (and leave init behind)
            cudaEvent_t e0, e1;
            ck(cudaEventCreate(&e0), "event create");
            ck(cudaEventCreate(&e1), "event create");
            ck(cudaEventRecord(e0), "record");
            auto t0 = std::chrono::steady_clock::now();
            // Actions are uploaded once so the timed loop measures the step
            // kernel and its launch, not a 4-byte H2D per step.
            for (int i = 0; i < STEPS; i++) puf_step(b.envs_d);
            ck(cudaDeviceSynchronize(), "bench sync");
            auto t1 = std::chrono::steady_clock::now();
            ck(cudaEventRecord(e1), "record");
            ck(cudaEventSynchronize(e1), "event sync");
            float ms = 0.0f;
            ck(cudaEventElapsedTime(&ms, e0, e1), "elapsed");
            double wall = std::chrono::duration<double>(t1 - t0).count();
            std::printf("F. n=%5d: %8.0f env-steps/s wall (%.3f ms/step for %d envs, %.2f us/env-step), "
                        "%.3f ms/kernel by events, %.2f GB device state\n", n,
                        (double)n * STEPS / wall, wall * 1000.0 / STEPS, n, wall * 1e6 / STEPS / n,
                        ms / STEPS, (double)n * sizeof(Env) / 1073741824.0);
            // reset kernel cost
            ck(cudaEventRecord(e0), "record");
            for (int i = 0; i < STEPS; i++) puf_reset(b.envs_d);
            ck(cudaDeviceSynchronize(), "reset bench sync");
            ck(cudaEventRecord(e1), "record");
            ck(cudaEventSynchronize(e1), "event sync");
            ck(cudaEventElapsedTime(&ms, e0, e1), "elapsed");
            std::printf("F. n=%5d: reset %d envs in %.3f ms/kernel (%.2f us/env)\n", n, n, ms / STEPS,
                        ms * 1000.0 / STEPS / n);
            ck(cudaEventDestroy(e0), "destroy");
            ck(cudaEventDestroy(e1), "destroy");
        }

        // unlock_all = 0 on the throughput path: the fresh-save LOCKED loot pool
        // (brotato_loot.h:449) changes which items the shop draws, so run it in the
        // dense start_wave=20 arena through the wave_ovr replay lane (waves end, the
        // Demon reaches its shop) and compare the whole batch against the host twin
        // afterwards -- the n-sweep rows above never check parity.
        {
            const int N = 64, STEPS = 400;
            Batch b(N, ZONE, SHOP_STEPS, "demon", "weapon_ghost_scepter_1", 1, 1, 20, 1, 0, 2.0f, 0);
            Ref r(N, ZONE, SHOP_STEPS, BT_CHARACTER_DEMON,
                  (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"), 1, 1, 20, 1,
                  "demon", "weapon_ghost_scepter_1", 2.0f, 0);
            std::vector<int> acts(N);
            b.pull_all_envs();
            for (int i = 0; i < N; i++)
                require(b.env(i)->state.lock_default_items == 1,
                        "unlock_all=0 must reach the device state on the throughput path", i);
            cudaEvent_t e0, e1;
            ck(cudaEventCreate(&e0), "event create");
            ck(cudaEventCreate(&e1), "event create");
            ck(cudaEventRecord(e0), "record");
            for (int t = 0; t < STEPS; t++) {
                for (int i = 0; i < N; i++) acts[i] = action_for(t, i);
                b.set_actions(acts.data());
                puf_step(b.envs_d);
                for (int i = 0; i < N; i++) r.step(i, acts[i]);
            }
            ck(cudaDeviceSynchronize(), "locked-pool bench sync");
            ck(cudaEventRecord(e1), "record");
            ck(cudaEventSynchronize(e1), "event sync");
            float ms = 0.0f;
            ck(cudaEventElapsedTime(&ms, e0, e1), "elapsed");
            std::string bad_lock = compare_batch(b, r);
            if (!bad_lock.empty()) fail("unlock_all=0 throughput run CPU/CUDA parity: " + bad_lock);
            std::printf("F. unlock_all=0 (locked loot pool): n=%d x %d steps, %.3f ms/step (%.2f us/env-step) "
                        "by events, every field bit-exact vs the host\n",
                        N, STEPS, ms / STEPS, ms * 1000.0f / STEPS / N);
            ck(cudaEventDestroy(e0), "destroy");
            ck(cudaEventDestroy(e1), "destroy");
        }
    }


    // -----------------------------------------------------------------------
    // G. cross-build trajectory digest: same schedule as
    // tests/brotato_traj_hash.cpp, so the digest can be compared against that
    // tool built with the CPU build's flags (clang -O2 -mavx2 -mfma).
    // -----------------------------------------------------------------------
    {
        const int N = 8, STEPS = 1500;
        Batch b(N, ZONE, SHOP_STEPS, "bull", "none");
        Ref r(N, ZONE, SHOP_STEPS, BT_CHARACTER_BULL, BT_WEAPON_NONE);
        unsigned long long host_acc = 1469598103934665603ull, dev_acc = 1469598103934665603ull;
        for (int t = 0; t < STEPS; t++) {
            std::vector<int> acts(N);
            for (int i = 0; i < N; i++) acts[i] = action_for(t, i);
            b.set_actions(acts.data());
            for (int i = 0; i < N; i++) r.step(i, acts[i]);
            b.step();
            b.pull_rewards();
            b.pull_all_envs();
            for (int i = 0; i < N; i++) {
                g_traj = host_acc;
                hmix(&r.obs[(size_t)i * BT_OBS_SIZE], BT_OBS_SIZE * sizeof(float));
                hmix_f(r.rew[i]);
                hmix_f(r.term[i]);
                hmix_state(r.s[i], i, t);
                host_acc = g_traj;
                g_traj = dev_acc;
                hmix(b.ob(i), BT_OBS_SIZE * sizeof(float));
                hmix_f(b.rew_h[i]);
                hmix_f(b.term_h[i]);
                hmix_state(b.env(i)->state, i, t);
                dev_acc = g_traj;
            }
        }
        require(host_acc == dev_acc, "host and device trajectory digests must agree");
        std::printf("G. trajectory digest (8 envs x %d steps, bull+none): host 0x%016llx device 0x%016llx "
                    "-- compare with tests/brotato_traj_hash.cpp built with the CPU build's flags\n",
                    STEPS, host_acc, dev_acc);
    }

    if (BENCH) {
        // F2. per-step kernel cost vs the phase the environments are in. The
        // phases differ per env (each has its own RNG/actions), so a step is
        // bucketed by how many envs are in shop / level-up, which is how much
        // of the batch pays the shop or level-up branch of bt_core_step.
        {
            const int N = 64, STEPS = 4000;
            Batch b(N, ZONE, SHOP_STEPS, "demon", "weapon_ghost_scepter_1");
            Ref r(N, ZONE, SHOP_STEPS, BT_CHARACTER_DEMON,
                  (unsigned short)bt_weapon_id_from_name("weapon_ghost_scepter_1"));
            std::vector<int> acts(N);
            std::vector<cudaEvent_t> ev(2 * STEPS);
            std::vector<double> ms(STEPS, 0.0);
            std::vector<int> shop_n(STEPS, 0), lvl_n(STEPS, 0), combat_n(STEPS, 0);
            for (int i = 0; i < 2 * STEPS; i++) ck(cudaEventCreate(&ev[i]), "event create");
            for (int t = 0; t < STEPS; t++) {
                for (int i = 0; i < N; i++) {
                    acts[i] = action_for(t, i);
                    shop_n[t] += r.s[i].phase == 1;
                    lvl_n[t] += r.s[i].phase == 2;
                    combat_n[t] += r.s[i].phase == 0;
                }
                b.set_actions(acts.data());
                ck(cudaEventRecord(ev[2 * t]), "record");
                puf_step(b.envs_d);
                ck(cudaEventRecord(ev[2 * t + 1]), "record");
                for (int i = 0; i < N; i++) r.step(i, acts[i]);
            }
            ck(cudaDeviceSynchronize(), "profile sync");
            double combat_sum = 0, shop_sum = 0, lvl_sum = 0, mixed_sum = 0;
            int combat_steps = 0, shop_steps = 0, lvl_steps = 0, mixed_steps = 0;
            for (int t = 0; t < STEPS; t++) {
                float v = 0.0f;
                ck(cudaEventElapsedTime(&v, ev[2 * t], ev[2 * t + 1]), "elapsed");
                ms[t] = v;
                if (shop_n[t] + lvl_n[t] > 0) {
                    if (shop_n[t] > lvl_n[t]) { shop_sum += v; shop_steps++; }
                    else { lvl_sum += v; lvl_steps++; }
                } else if (combat_n[t] == N) { combat_sum += v; combat_steps++; }
                else { mixed_sum += v; mixed_steps++; }
            }
            for (int i = 0; i < 2 * STEPS; i++) cudaEventDestroy(ev[i]);
            b.pull_obs();
            std::string bad = compare_batch(b, r);
            if (!bad.empty()) fail("F2 profile trajectory parity: " + bad);
            std::printf("F2. n=%d step kernel time by phase mix over %d steps (%.2f us/env-step overall):\n",
                        N, STEPS, 1000.0 * (combat_sum + shop_sum + lvl_sum + mixed_sum) / STEPS / N);
            if (combat_steps) std::printf("      all-combat steps: %5d (%.0f%%), %.3f ms/step = %.2f us/env\n",
                                          combat_steps, 100.0 * combat_steps / STEPS, combat_sum / combat_steps,
                                          1000.0 * combat_sum / combat_steps / N);
            if (shop_steps) std::printf("      shop > levelup steps: %5d (%.0f%%), %.3f ms/step = %.2f us/env (caveat: mixed batch)\n",
                                        shop_steps, 100.0 * shop_steps / STEPS, shop_sum / shop_steps,
                                        1000.0 * shop_sum / shop_steps / N);
            if (lvl_steps) std::printf("      levelup >= shop steps: %5d (%.0f%%), %.3f ms/step = %.2f us/env (caveat: mixed batch)\n",
                                       lvl_steps, 100.0 * lvl_steps / STEPS, lvl_sum / lvl_steps,
                                       1000.0 * lvl_sum / lvl_steps / N);
            if (mixed_steps) std::printf("      other steps: %5d (%.0f%%), %.3f ms/step\n", mixed_steps,
                                         100.0 * mixed_steps / STEPS, mixed_sum / mixed_steps);
        }

    }

    std::printf("PASS: device kernel is bit-exact with the host core over every compared field\n");
    return 0;
}
