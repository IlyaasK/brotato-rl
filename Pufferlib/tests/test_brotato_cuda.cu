// CPU-vs-CUDA parity and throughput test for the Brotato CUDA backend.
//
// Compile (from the repository root, on this host; sm_120 = RTX 5070):
//
//   nvcc -O2 -std=c++17 -arch=sm_120 --fmad=false -Xcompiler=-ffp-contract=off \
//     -Xcompiler=-Wno-narrowing -Xcompiler=-Wno-unreachable-code \
//     --diag-suppress=2361 --diag-suppress=111 --diag-suppress=128 \
//     -I. -Isrc -Iocean/brotato -Ivendor -Iraylib-5.5_linux_amd64/include \
//     tests/test_brotato_cuda.cu raylib-5.5_linux_amd64/lib/libraylib.a \
//     -lm -pthread -lGL -o /tmp/test_brotato_cuda
//   /tmp/test_brotato_cuda
//
// COMPILE TIME: this TU is the slowest build in the tree, because it has to
// codegen the whole shared core.  Measured on this host (sm_120, nvcc 13.4):
// nvcc ~10.5 min, of which ptxas ~9 min, of which ptxas -v charges ~500 s to
// bt_gpu_step_kernel ALONE (that entry is where ptxas inlines + register-
// allocates the hot path) against 15-31 s for bt_gpu_init_kernel, 16-27 s for
// bt_gpu_reset_kernel and <1 s for everything else.  The step kernel's 254
// registers / 6048 B stack are the same with and without the cold-path noinline
// guards in ocean/brotato/brotato_core.h (bt_enter_wave, bt_core_reset,
// `#if defined(__METAL_VERSION__) || defined(__CUDACC__)`), which took this TU's
// PTX from 554,479 to 428,517 lines and the two cold kernels from 74,203/74,094
// to 9,322/9,247 lines -- worth having, but it does not cut the ~500 s, because
// that is the step kernel's own compile and it is per TU.  Do not "fix" it with
// -Xptxas -O1/-O2 either: they measure the same ~8-9 min as -O3.  The real lever
// is compiling that one kernel once per tree (separate device TU + -rdc +
// nvlink) or caching the per-TU results (ccache).
//
// -ffp-contract=off on the host pass and --fmad=false on the device pass are
// REQUIRED for parity: the core must not contract a multiply-add on either side.
// (build.sh already pins both for brotato; the line above mirrors it.)
// rayLIB is only needed because ocean/brotato/brotato.cu also carries the
// renderer, which this test never calls.
//
// What each layer proves (mirrors tests/test_brotato_metal.mm):
//
//   A. handle/create contract - the puf_vec_create path (device Env array, one
//      kernel thread per env, one-shot bt_core_init per env with the same seed
//      the CPU env uses), puf_reset semantics (fresh episode, obs rewritten,
//      rewards/terminals zeroed, log preserved), and the Env.log aliasing
//      contract the trainer's device log-reduce depends on.
//   B. device determinism - two identically configured batches stay
//      bit-identical over the same action sequence.
//   C. CPU vs CUDA, strict and per step - every observation float, the reward,
//      the terminal flag and EVERY BtState field (403 fields, byte-exact, with
//      the 266 bytes of struct padding excluded, table generated by
//      tests/gen_brotato_state_fields.py) compared against the same core
//      compiled for the host in this same translation unit, over a batch of
//      environments with varied pseudo-random action sequences.
//      Any difference is a hard failure that names the step, the environment,
//      field and the first differing byte.  Thirteen Demon-first profiles:
//      demon+ghost_scepter_1, the same through the replay lane's wave-duration
//      override (`wave_ovr`, the instant_waves hook), the same wave_ovr run with
//      `unlock_all = 0` (the fresh-save LOCKED loot pool), a deep immortal
//      `start_wave = 40 endless invulnerable` run whose shop schedule walks the
//      LOCK actions 21..24 and REROLL (4) on a fully locked and on a partially
//      locked 4-slot shop (the fully locked one is the state in which the device
//      build mis-addressed bt_progress_roll_shop's locked-offer snapshot), the
//      same ENDLESS, then the same with the optional non-default keys
//      `audio_rng = 0`,
//      `particles_rng = 0`, `start_wave = 20`, all three together, all three +
//      ENDLESS, then bull+none and knight+hatchet_2.
//      Phase coverage: combat and a terminal episode are required of EVERY
//      profile; shop and level-up are accumulated across the profile set (the
//      Demon dies in ~600-860 ticks, before any 20 s wave ends, so none of its
//      campaign/endless profiles can reach either) and hard-required on the
//      wave_ovr Demon profile, whose waves end before death and therefore
//      exercise the Demon's HP-currency shop and its level-up offers on the
//      device.  The immortal `invulnerable` profile is the one documented
//      exception: it cannot end an episode (no death, no endless win), so it
//      requires the shop and that its LOCK actions took effect instead.
//      Every env's full state is compared every 512 steps and envs
//      0..3 every 8 steps.
//   D. profile config reaches the kernel - Bull+none, Knight+hatchet and
//      Demon+ghost scepter: the ids must arrive in the kernel, produce the
//      host's initial state, differ from Bull, and stay in parity through
//      combat.
//   E. the device transcendental port is bit-exact against this host's libm
//      (brotato_math_cuda.h): sinf/cosf/atan2f/sqrtf over a large sample
//      (BT_MATH_SAMPLES, default 8M per function) drawn from the whole float
//      range plus the ranges the core actually produces. The exhaustive
//      all-2^32-inputs sweep lives in the throwaway tool described in
//      ocean/brotato/brotato_math_cuda.h.
//   F. throughput/occupancy - env steps/sec and per-kernel time for batch
//      sizes that fit the device, plus registers/local memory/blocks per SM
//      for the step kernel; F2 then buckets the per-step kernel time by the
//      phase the batch is in (all-combat vs shop vs level-up dominated).
//      Skip both with BT_BENCH=0.
//   G. cross-build trajectory digest - the same 8 env x 1500 step schedule as
//      tests/brotato_traj_hash.cpp, printed as one FNV-1a digest, so the CUDA
//      backend can be compared against that tool built with the flags the CPU
//      environment uses (clang -O2 -mavx2 -mfma; see the tool's header).
//   H. two cases that used to be exercised only outside the real wiring: the
//      experimental lane scheduler driven through puf_vec_create(warp_step=1) ->
//      puf_reset/puf_step against the host core, with a HARD requirement that a
//      terminal tick is reached AND that the build really armed the warp path
//      (compile with -DBTFW_EXPERIMENTAL_LANE_SCHED; without the macro the block
//      is compiled out and the serial path is used), and a puf_bind_action_mask
//      row WIDER than BT_ACTIONS whose head must match bt_action_mask and whose
//      poisoned tail must come back zero-filled.
//      STILL NOT COVERED HERE, do not read this harness as closing them: the
//      capacity latch TRAPS (a forced overflow aborts the kernel, so it cannot be
//      observed from inside this process; tests/test_brotato_capacity.cu builds a
//      tiny-bound binary and asserts the trap there -- the env-0 high-bit classes,
//      the warp path never arming the latch, and puf_log being read only after the
//      learner rather than at the rollout boundary are still open), and
//      multi-SM warp repeats.  `unlock_all = 0` IS covered: layer C runs a
//      locked-pool profile (device state + full parity) and layer F runs a
//      locked-pool throughput row with a bit-exact batch compare.
//
// Environment knobs: BT_MATH_SAMPLES=N, BT_BENCH=0, BT_PARITY_STEPS=N,
// BT_SKIP_TRAJECTORY=1 (layers A/B/D/E/F/G only).
//
// KEEPING THIS VALID AS THE CORE CHANGES (obs/action schema, state layout):
//   * everything here is written against BT_OBS_SIZE, BT_ACTIONS, sizeof(Env)
//     and the generated field list, never against literal counts, so an
//     observation/action rescale (e.g. the planned 198/31 + action mask) needs
//     no edit beyond, if puf_vec_create grows an action-mask buffer, passing
//     that buffer in Batch's constructor;
//   * the field list lives in tests/brotato_state_fields.inc and is generated
//     from the struct text by tests/gen_brotato_state_fields.py; when BtState
//     changes, regenerate it and the coverage check below fails loudly instead
//     of silently skipping the new fields:
//       python3 tests/gen_brotato_state_fields.py \
//           ocean/brotato/brotato_state.h > tests/brotato_state_fields.inc
//   * a difference in *layout* alone never matters: fields are compared by
//     byte range inside their own struct, so PerfMemory's compaction is
//     transparent to this test.

